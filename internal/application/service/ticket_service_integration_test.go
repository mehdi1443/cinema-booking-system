func TestTicketPDFMinIOIntegration(t *testing.T) {
	endpoint := os.Getenv("TICKET_INTEGRATION_MINIO_ENDPOINT")
	if endpoint == "" {
		t.Skip("TICKET_INTEGRATION_MINIO_ENDPOINT is not set")
	}
	env := &bootstrap.Environment{Storage: bootstrap.Storage{
		AccessKey: os.Getenv("TICKET_INTEGRATION_MINIO_ACCESS_KEY"),
		SecretKey: os.Getenv("TICKET_INTEGRATION_MINIO_SECRET_KEY"),
		Region:    "us-east-1",
		Endpoint:  endpoint,
		Buckets: bootstrap.BucketName{
			MoviePoster: "cinema-movie-posters", MovieTrailer: "cinema-movie-trailers",
			ActorPhoto: "cinema-actor-photos", CinemaPhoto: "cinema-cinema-photos",
			TicketPDF: "cinema-ticket-pdfs",
		},
	}}
	storage, err := miniorepo.NewS3Storage(env)
	if err != nil {
		t.Fatalf("initialize MinIO: %v", err)
	}

	start := time.Now().Add(24 * time.Hour)
	ticket := &entity.Ticket{
		BaseEntity: entity.BaseEntity{ID: 991_001}, ReservationID: 991_002, PaymentID: 991_003,
		UserID: 991_004, Code: "ct_minio_integration", Status: enum.TicketActive,
		Reservation: &entity.Reservation{BaseEntity: entity.BaseEntity{ID: 991_002}, Items: []entity.ReservationItem{{
			ShowtimeSeat: &entity.ShowtimeSeat{RowLabel: "A", SeatNumber: 1, SeatType: enum.SeatTypeStandard},
		}}, Showtime: &entity.Showtime{StartsAt: start, EndsAt: start.Add(2 * time.Hour),
			Movie: &entity.Movie{Title: "تست بلیط"}, Hall: &entity.Hall{Name: "سالن تست", Cinema: &entity.Cinema{Name: "سینمای تست"}}}},
	}
	repo := &ticketMemoryRepository{ticket: ticket}
	service := NewTicketService(repo, storage, discardLogger{})
	if err := service.EnsurePDFForPayment(context.Background(), ticket.PaymentID); err != nil {
		t.Fatalf("generate and upload PDF: %v", err)
	}
	if repo.ticket.PDFObjectKey == nil || repo.ticket.PDFURL == nil || repo.ticket.PDFGeneratedAt == nil {
		t.Fatal("PDF storage metadata was not persisted")
	}
	t.Cleanup(func() { _ = storage.DeleteObject(context.Background(), enum.TicketPDF, *repo.ticket.PDFObjectKey) })

	download, err := service.PDF(context.Background(), ticket.ID, ticket.UserID, false)
	if err != nil {
		t.Fatalf("create presigned URL: %v", err)
	}
	response, err := http.Get(download.URL) // #nosec G107 -- URL is generated by the test MinIO instance.
	if err != nil {
		t.Fatalf("download presigned PDF: %v", err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		t.Fatalf("download status: %s", response.Status)
	}
	header := make([]byte, 5)
	if _, err := io.ReadFull(response.Body, header); err != nil {
		t.Fatalf("read downloaded PDF: %v", err)
	}
	if string(header) != "%PDF-" {
		t.Fatalf("downloaded object is not a PDF: %q", header)
	}

	publicURLResponse, err := http.Get(*repo.ticket.PDFURL) // #nosec G107 -- URL is generated by the test MinIO instance.
	if err != nil {
		t.Fatalf("check private object URL: %v", err)
	}
	defer publicURLResponse.Body.Close()
	if publicURLResponse.StatusCode != http.StatusForbidden {
		t.Fatalf("ticket PDF bucket is not private: status=%s", publicURLResponse.Status)
	}
}

type ticketMemoryRepository struct{ ticket *entity.Ticket }

func (r *ticketMemoryRepository) GetTicket(_ context.Context, id int64) (*entity.Ticket, error) {
	if r.ticket.ID != id {
		return nil, nil
	}
	return r.ticket, nil
}

func (r *ticketMemoryRepository) GetTicketByPaymentID(_ context.Context, paymentID int64) (*entity.Ticket, error) {
	if r.ticket.PaymentID != paymentID {
		return nil, nil
	}
	return r.ticket, nil
}

func (r *ticketMemoryRepository) ListUserTickets(context.Context, int64, int, int) ([]entity.Ticket, int64, error) {
	return []entity.Ticket{*r.ticket}, 1, nil
}

func (r *ticketMemoryRepository) SetTicketPDF(_ context.Context, _ int64, url, objectKey string, generatedAt time.Time) (*entity.Ticket, error) {
	r.ticket.PDFURL = &url
	r.ticket.PDFObjectKey = &objectKey
	r.ticket.PDFGeneratedAt = &generatedAt
	return r.ticket, nil
}

func (r *ticketMemoryRepository) ConsumeTicket(context.Context, string, int64, bool, time.Time) (*entity.Ticket, error) {
	return r.ticket, nil
}

type discardLogger struct{}

func (discardLogger) Debug(context.Context, string, ...domainlogger.Field) {}
func (discardLogger) Info(context.Context, string, ...domainlogger.Field)  {}
func (discardLogger) Warn(context.Context, string, ...domainlogger.Field)  {}
func (discardLogger) Error(context.Context, string, ...domainlogger.Field) {}
func (discardLogger) With(...domainlogger.Field) domainlogger.Logger       { return discardLogger{} }
