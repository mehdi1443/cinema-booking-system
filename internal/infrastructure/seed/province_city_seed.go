type AddressSeeder struct {
	provinceRepo repository_contract.ProvinceRepository
	cityRepo     repository_contract.CityRepository
}

func NewAddressSeeder(
	provinceRepo repository_contract.ProvinceRepository,
	cityRepo repository_contract.CityRepository,
) *AddressSeeder {
	return &AddressSeeder{
		provinceRepo: provinceRepo,
		cityRepo:     cityRepo,
	}
}

func (s *AddressSeeder) Seed(ctx context.Context) error {
	for provinceName, cityNames := range provinceWithCities {
		province, err := s.provinceRepo.GetByName(ctx, provinceName)
		if err != nil && !errors.Is(err, exception.ErrProvinceNotFound) {
			return fmt.Errorf("failed to check province %s: %w", provinceName, err)
		}

		if errors.Is(err, exception.ErrProvinceNotFound) {
			province = &entity.Province{
				Name: provinceName,
			}
			if err := s.provinceRepo.Create(ctx, province); err != nil {
				return fmt.Errorf("failed to create province %s: %w", provinceName, err)
			}
		}

		for _, cityName := range cityNames {
			_, err := s.cityRepo.GetByNameAndProvinceID(ctx, cityName, province.ID)
			if err != nil && !errors.Is(err, exception.ErrCityNotFound) {
				return fmt.Errorf("failed to check city %s: %w", cityName, err)
			}

			if errors.Is(err, exception.ErrCityNotFound) {
				city := &entity.City{
					Name:       cityName,
					ProvinceID: province.ID,
				}
				if err := s.cityRepo.Create(ctx, city); err != nil {
					return fmt.Errorf("failed to create city %s: %w", cityName, err)
				}
			}
		}
	}

	return nil
}
