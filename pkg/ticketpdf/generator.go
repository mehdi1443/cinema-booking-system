package ticketpdf

import (
	"bytes"
	"errors"
	"fmt"
	"strings"
	"time"

	"github.com/go-fonts/dejavu/dejavusans"
	"github.com/go-fonts/dejavu/dejavusansbold"
	"github.com/signintech/gopdf"
	qrcode "github.com/skip2/go-qrcode"
)

const qrPayloadPrefix = "cinema-ticket:"

type Seat struct {
	Row    string
	Number int
	Type   string
}

type Data struct {
	TicketCode    string
	TicketID      int64
	ReservationID int64
	PaymentID     int64
	MovieTitle    string
	CinemaName    string
	HallName      string
	StartsAt      time.Time
	EndsAt        time.Time
	Seats         []Seat
}

func Generate(data Data) ([]byte, error) {
	if strings.TrimSpace(data.TicketCode) == "" || data.TicketID <= 0 || data.ReservationID <= 0 || data.PaymentID <= 0 {
		return nil, errors.New("invalid ticket PDF data")
	}

	qrPNG, err := qrcode.Encode(qrPayloadPrefix+data.TicketCode, qrcode.Medium, 512)
	if err != nil {
		return nil, fmt.Errorf("generate QR code: %w", err)
	}
	qrImage, err := gopdf.ImageHolderByBytes(qrPNG)
	if err != nil {
		return nil, fmt.Errorf("load QR code image: %w", err)
	}

	var pdf gopdf.GoPdf
	pdf.Start(gopdf.Config{Unit: gopdf.UnitPT, PageSize: *gopdf.PageSizeA4})
	pdf.SetInfo(gopdf.PdfInfo{
		Title:        "Cinema ticket " + data.TicketCode,
		Author:       "Cinema Ticket",
		Subject:      "Cinema admission ticket",
		Creator:      "Cinema Ticket API",
		Producer:     "Cinema Ticket API",
		CreationDate: time.Now(),
	})
	if err := pdf.AddTTFFontData("Regular", dejavusans.TTF); err != nil {
		return nil, fmt.Errorf("add regular font: %w", err)
	}
	if err := pdf.AddTTFFontData("Bold", dejavusansbold.TTF); err != nil {
		return nil, fmt.Errorf("add bold font: %w", err)
	}
	pdf.AddPage()

	// Header
	pdf.SetFillColor(15, 23, 42)
	pdf.RectFromUpperLeftWithStyle(0, 0, 595, 132, "F")
	pdf.SetFillColor(14, 165, 233)
	pdf.RectFromUpperLeftWithStyle(40, 33, 8, 67, "F")
	if err := setText(&pdf, "Bold", 28, 255, 255, 255, 62, 35, 350, 36, "CINEMA TICKET"); err != nil {
		return nil, err
	}
	if err := setText(&pdf, "Regular", 10, 148, 163, 184, 63, 78, 350, 18, "DIGITAL ADMISSION PASS"); err != nil {
		return nil, err
	}
	if err := setText(&pdf, "Bold", 11, 255, 255, 255, 438, 52, 115, 22, "ADMIT ONE"); err != nil {
		return nil, err
	}

	// Main ticket card.
	pdf.SetStrokeColor(203, 213, 225)
	pdf.SetFillColor(248, 250, 252)
	pdf.RectFromUpperLeftWithStyle(40, 166, 515, 410, "DF")
	if err := setText(&pdf, "Bold", 23, 15, 23, 42, 65, 191, 310, 34, fallback(data.MovieTitle, "Movie")); err != nil {
		return nil, err
	}
	if err := setText(&pdf, "Regular", 11, 71, 85, 105, 65, 231, 310, 18, joinNonEmpty(" / ", data.CinemaName, data.HallName)); err != nil {
		return nil, err
	}

	labelRows := [][2]string{
		{"DATE", data.StartsAt.Format("Mon, 02 Jan 2006")},
		{"TIME", data.StartsAt.Format("15:04") + " - " + data.EndsAt.Format("15:04 MST")},
		{"SEATS", formatSeats(data.Seats)},
		{"TICKET ID", fmt.Sprintf("#%d", data.TicketID)},
		{"RESERVATION", fmt.Sprintf("#%d", data.ReservationID)},
		{"PAYMENT", fmt.Sprintf("#%d", data.PaymentID)},
	}
	y := 286.0
	for _, row := range labelRows {
		if err := setText(&pdf, "Bold", 8, 100, 116, 139, 65, y, 105, 15, row[0]); err != nil {
			return nil, err
		}
		if err := setText(&pdf, "Regular", 11, 15, 23, 42, 165, y-2, 210, 18, row[1]); err != nil {
			return nil, err
		}
		y += 39
	}

	// QR area.
	pdf.SetFillColor(255, 255, 255)
	pdf.RectFromUpperLeftWithStyle(394, 190, 136, 186, "F")
	if err := pdf.ImageByHolder(qrImage, 407, 202, &gopdf.Rect{W: 110, H: 110}); err != nil {
		return nil, fmt.Errorf("draw QR code: %w", err)
	}
	if err := setText(&pdf, "Bold", 7, 71, 85, 105, 401, 321, 122, 13, "SCAN AT ENTRANCE"); err != nil {
		return nil, err
	}
	if err := setText(&pdf, "Regular", 6.5, 100, 116, 139, 401, 342, 122, 12, truncate(data.TicketCode, 28)); err != nil {
		return nil, err
	}

	// Footer and usage notes.
	pdf.SetFillColor(14, 165, 233)
	pdf.RectFromUpperLeftWithStyle(40, 610, 515, 4, "F")
	if err := setText(&pdf, "Bold", 10, 15, 23, 42, 55, 637, 485, 18, "IMPORTANT"); err != nil {
		return nil, err
	}
	if err := setText(&pdf, "Regular", 8.5, 71, 85, 105, 55, 665, 485, 20, "Present this QR code at the entrance. Each ticket is valid only once."); err != nil {
		return nil, err
	}
	if err := setText(&pdf, "Regular", 8.5, 71, 85, 105, 55, 692, 485, 20, "Keep this PDF private. Its QR code is your admission credential."); err != nil {
		return nil, err
	}
	if err := setText(&pdf, "Regular", 7.5, 148, 163, 184, 40, 778, 515, 16, "Generated by Cinema Ticket API", gopdf.Center); err != nil {
		return nil, err
	}

	var out bytes.Buffer
	if err := pdf.Write(&out); err != nil {
		return nil, fmt.Errorf("write PDF: %w", err)
	}
	return out.Bytes(), nil
}

func setText(pdf *gopdf.GoPdf, font string, size float64, r, g, b uint8, x, y, w, h float64, value string, align ...int) error {
	if err := pdf.SetFont(font, "", size); err != nil {
		return fmt.Errorf("set PDF font: %w", err)
	}
	pdf.SetTextColor(r, g, b)
	pdf.SetXY(x, y)
	value = truncate(value, 70)
	textAlign := gopdf.Left | gopdf.Middle
	if len(align) != 0 {
		textAlign = align[0] | gopdf.Middle
	} else if containsRTL(value) {
		value = gopdf.ToArabic(value)
		textAlign = gopdf.Right | gopdf.Middle
	}
	if err := pdf.CellWithOption(&gopdf.Rect{W: w, H: h}, value, gopdf.CellOption{Align: textAlign}); err != nil {
		return fmt.Errorf("draw PDF text: %w", err)
	}
	return nil
}

func containsRTL(value string) bool {
	for _, r := range value {
		if (r >= '\u0600' && r <= '\u06ff') || (r >= '\u0750' && r <= '\u077f') || (r >= '\u08a0' && r <= '\u08ff') {
			return true
		}
	}
	return false
}

func formatSeats(seats []Seat) string {
	values := make([]string, 0, len(seats))
	for _, seat := range seats {
		label := fmt.Sprintf("%s-%d", strings.TrimSpace(seat.Row), seat.Number)
		if strings.TrimSpace(seat.Type) != "" {
			label += " (" + strings.TrimSpace(seat.Type) + ")"
		}
		values = append(values, label)
	}
	if len(values) == 0 {
		return "Not specified"
	}
	return strings.Join(values, ", ")
}

func joinNonEmpty(separator string, values ...string) string {
	result := make([]string, 0, len(values))
	for _, value := range values {
		if value = strings.TrimSpace(value); value != "" {
			result = append(result, value)
		}
	}
	return strings.Join(result, separator)
}

func fallback(value, defaultValue string) string {
	if strings.TrimSpace(value) == "" {
		return defaultValue
	}
	return value
}

func truncate(value string, max int) string {
	runes := []rune(strings.TrimSpace(value))
	if len(runes) <= max {
		return string(runes)
	}
	return string(runes[:max-1]) + "…"
}
